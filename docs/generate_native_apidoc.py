"""Regenerate owned C++ reference pages from the current native headers."""

from pathlib import Path
import re


GENERATED_MARKER = ".. Generated by docs/generate_native_apidoc.py; do not edit."
NATIVE_MODULES = ("dic", "strain")


def is_generated_native_page(page: Path) -> bool:
    """Recognise owned output and the exact bare legacy generator templates.

    The legacy templates were checked into Git. Additional authored content
    makes a page manual and protects it from this one-time ownership migration.
    """
    if page.is_symlink() or not page.is_file():
        return False
    text = page.read_text(encoding="utf-8")
    if text.startswith(GENERATED_MARKER + "\n"):
        return True
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    if len(lines) < 4 or not re.fullmatch(r"=+", lines[1]):
        return False
    if re.fullmatch(r"\w+\.hpp", lines[0]):
        return (
            lines[2] == f".. doxygenfile:: {lines[0]}"
            and lines[3] == ":project: pyvale"
            and (
                len(lines) == 4
                or (len(lines) == 5 and lines[4].startswith(":path: "))
            )
        )
    if page.stem.startswith("cpp_"):
        module = page.stem.removeprefix("cpp_")
        return (
            lines[0] == module
            and lines[2] == ".. toctree::"
            and all(
                line in {":caption: C++ Source Files", ":maxdepth: 1"}
                or re.fullmatch(rf"{re.escape(module)}/\w+\.rst", line)
                for line in lines[3:]
            )
        )
    return False


def generate_native_api_docs(repo_root: Path) -> None:
    """Publish current header pages and remove only recognised generated output.

    Generated pages carry an ownership marker. Remove the marker before editing
    one by hand; its new source annotation distinguishes it from legacy output.
    Failed publication restores previous generated files and removes new files.
    """
    repo_root = repo_root.resolve()
    if not (repo_root / "src/pyvale").is_dir():
        raise FileNotFoundError(f"PyVale source directory is missing: {repo_root}")
    output = repo_root / "docs/source/cpp"
    planned: dict[Path, str] = {}
    for module in NATIVE_MODULES:
        headers = sorted((repo_root / "src/pyvale" / module / "cpp").glob("*.hpp"))
        if not headers:
            continue
        entries = []
        for header in headers:
            page = output / module / f"{header.stem}.rst"
            source = header.relative_to(repo_root).as_posix()
            directive = f".. doxygenfile:: {header.name}\n   :project: pyvale\n"
            if module == "dic" and header.name == "stereomatching.hpp":
                # Breathe renders a file's namespace as a C++ type. Both stereo
                # headers share that namespace, so index it once in stereoutil
                # and document this header's entry point directly instead.
                directive = (
                    ".. doxygenfunction:: stereo::matching\n   :project: pyvale\n"
                )
            planned[page] = (
                f"{GENERATED_MARKER}\n\n{header.name}\n"
                f"{'=' * len(header.name)}\n\nSource: :file:`{source}`.\n\n{directive}"
            )
            entries.append(f"   {module}/{header.stem}")
        title = f"{module.upper() if module == 'dic' else 'Strain'} native headers"
        planned[output / f"cpp_{module}.rst"] = (
            f"{GENERATED_MARKER}\n\n{title}\n{'=' * len(title)}\n\n"
            f"Header reference for the {module} implementation.\n\n"
            ".. toctree::\n   :maxdepth: 1\n\n" + "\n".join(entries) + "\n"
        )

    owned = {
        page: page.read_bytes()
        for page in output.rglob("*.rst")
        if is_generated_native_page(page)
    }
    published: list[Path] = []
    try:
        for page, content in planned.items():
            if page.is_symlink() or (page.exists() and page not in owned):
                print(f"Preserving maintained native API page: {page.name}")
                continue
            page.parent.mkdir(parents=True, exist_ok=True)
            published.append(page)
            page.write_text(content, encoding="utf-8")
        for page in owned.keys() - planned.keys():
            page.unlink()
    except BaseException:
        for page in published:
            if page not in owned:
                page.unlink(missing_ok=True)
        for page, content in owned.items():
            page.write_bytes(content)
        raise
    print(
        f"Generated {len(published)} native API pages; "
        f"removed {len(owned.keys() - planned.keys())} stale pages."
    )


if __name__ == "__main__":
    generate_native_api_docs(Path(__file__).resolve().parents[1])
