"""Regenerate Python API pages without overwriting maintained documentation."""

import re
import shutil
import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory

GENERATED_MARKER = ".. Generated by docs/apidoc.sh; do not edit."
MODULE_NAME = r"pyvale(?:\.[A-Za-z_]\w*)*"


def is_generated_page(page: Path) -> bool:
    """Recognise marked pages and the strict legacy sphinx-apidoc templates.

    Parameters
    ----------
    page : Path
        Candidate API page; symlinks are never treated as generated pages.

    Returns
    -------
    bool
        True for marked output or a legacy template containing only generated
        headings, API directives, standard options and module-name entries.
    """
    if page.is_symlink() or not page.is_file():
        return False
    try:
        text = page.read_text(encoding="utf-8")
    except UnicodeError:
        return False
    if text.startswith(GENERATED_MARKER + "\n"):
        return True
    if ".. automodule:: " not in text and ".. toctree::" not in text:
        return False
    module_titles = {
        page.stem,
        page.stem.removeprefix("pyvale."),
        page.stem.rsplit(".", 1)[-1],
    }
    headings = {
        title + suffix
        for title in module_titles
        for suffix in ("", " module", " package", ".py")
    }
    headings.update({"Subpackages", "Submodules", "Module contents"})
    options = {
        ":members:",
        ":undoc-members:",
        ":show-inheritance:",
        ":caption: Python Source Files",
        ":maxdepth: 1",
        ":maxdepth: 4",
        ".. toctree::",
    }
    return all(
        not line
        or line.replace("\\_", "_") in headings
        or line in options
        or re.fullmatch(r"[=~-]+", line)
        or re.fullmatch(MODULE_NAME, line)
        or re.fullmatch(r"\.\. automodule:: " + MODULE_NAME, line)
        for line in (line.strip() for line in text.splitlines())
    )


def format_api_page(text: str) -> str:
    """Apply the existing API landing-page layout and mark generated ownership.

    Parameters
    ----------
    text : str
        Fresh sphinx-apidoc reStructuredText.

    Returns
    -------
    str
        Marked page with compact package navigation and no unavailable Cython entry.
    """
    if text.splitlines()[0].endswith(" package"):
        text = text.split("\nModule contents\n", 1)[0]
        text = re.sub(r"^Submodules\n-+\n", "", text, flags=re.MULTILINE)
        text = re.sub(r" package$", "", text, flags=re.MULTILINE)
        text = text.replace(
            ".. toctree::\n", ".. toctree::\n   :caption: Python Source Files\n"
        )
        text = text.replace(":maxdepth: 4", ":maxdepth: 1")
    text = "".join(
        line for line in text.splitlines(True) if line.strip() != "pyvale.dic.dic2dcpp"
    )
    return GENERATED_MARKER + "\n\n" + text


def generate_api_docs(repo_root: Path) -> None:
    """Clear generated Python API pages, regenerate, and restore on failure.

    Parameters
    ----------
    repo_root : Path
        Git checkout containing docs/source and src/pyvale.

    Notes
    -----
    Only Git-ignored, untracked pyvale*.rst files recognised as generated output
    are cleared. Tracked pages and unrecognised manual pages are never published
    over. Generation uses staging and backup directories; failed regeneration
    restores the previous generated pages. Gallery, guide and C++ pages are outside
    the cleanup scope.

    Raises
    ------
    subprocess.CalledProcessError
        Git inspection or sphinx-apidoc fails.
    OSError
        API files cannot be read or published.
    RuntimeError
        Generation exits without producing the root API page.
    """
    repo_root = repo_root.resolve()
    source_dir = repo_root / "docs/source"
    package_dir = repo_root / "src/pyvale"
    tracked = subprocess.run(
        ["git", "ls-files", "-z", "--", "docs/source"],
        cwd=repo_root,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    tracked_paths = {repo_root / name for name in tracked.split("\0") if name}
    candidates = [
        page
        for page in source_dir.glob("pyvale*.rst")
        if re.fullmatch(MODULE_NAME + r"\.rst", page.name)
    ]
    generated_pages = []
    for page in candidates:
        if page in tracked_paths or not is_generated_page(page):
            continue
        ignored = subprocess.run(
            ["git", "check-ignore", "--quiet", "--", str(page)],
            cwd=repo_root,
            check=False,
        )
        if ignored.returncode == 0:
            generated_pages.append(page)
        elif ignored.returncode != 1:
            ignored.check_returncode()

    with TemporaryDirectory(prefix=".apidoc-", dir=repo_root / "docs") as temp_dir:
        temporary_dir = Path(temp_dir)
        backup_dir = temporary_dir / "backup"
        backup_dir.mkdir()
        staged_dir = temporary_dir / "generated"
        published_pages = []
        backed_up_pages = []
        try:
            for page in generated_pages:
                shutil.copy2(page, backup_dir / page.name)
                backed_up_pages.append(page)
                page.unlink()
            subprocess.run(
                [
                    sys.executable,
                    "-m",
                    "sphinx.ext.apidoc",
                    "--force",
                    "--separate",
                    "--output-dir",
                    str(staged_dir),
                    str(package_dir),
                    str(package_dir / "examples"),
                ],
                cwd=repo_root,
                check=True,
            )
            if not (staged_dir / "pyvale.rst").is_file():
                raise RuntimeError(
                    "sphinx-apidoc did not generate the root pyvale.rst page"
                )
            for page in sorted(staged_dir.glob("pyvale*.rst")):
                if page.name == "pyvale.dic.dic2dcpp.rst":
                    continue
                target = source_dir / page.name
                if target in tracked_paths or target.exists() or target.is_symlink():
                    print(f"Preserving maintained API page: {target.name}")
                    continue
                published_pages.append(target)
                target.write_text(
                    format_api_page(page.read_text(encoding="utf-8")), encoding="utf-8"
                )
        except BaseException:
            for page in published_pages:
                page.unlink(missing_ok=True)
            for page in backed_up_pages:
                if not page.exists() and not page.is_symlink():
                    shutil.copy2(backup_dir / page.name, page)
            raise
    print(
        f"Replaced {len(generated_pages)} old API pages; generated {len(published_pages)} pages."
    )


if __name__ == "__main__":
    generate_api_docs(Path(__file__).resolve().parents[1])
