"""Remove obsolete, generator-owned gallery pages before Sphinx-Gallery runs."""

from pathlib import Path
import re
import subprocess

from sphinx.application import Sphinx
from sphinx.util import logging


LOGGER = logging.getLogger(__name__)
GENERATED_MARKER = ".. THIS FILE WAS AUTOMATICALLY GENERATED BY SPHINX-GALLERY."


def is_ignored_artifact(path: Path, tracked: set[Path], repo_root: Path) -> bool:
    """Require an ordinary, untracked, Git-ignored file before deletion."""
    if path.is_symlink() or not path.is_file() or path in tracked:
        return False
    ignored = subprocess.run(
        ["git", "check-ignore", "--quiet", "--", str(path)],
        cwd=repo_root,
        check=False,
    )
    if ignored.returncode not in (0, 1):
        ignored.check_returncode()
    return ignored.returncode == 0


def clean_generated_galleries(
    source_dir: Path,
    example_dirs: list[str],
    gallery_dirs: list[str],
    *,
    ignore_pattern: str,
) -> list[Path]:
    """Delete only owned pages for removed examples or excluded helper modules.

    Tracked files, symlinks and pages without Sphinx-Gallery's ownership header
    are preserved. Companion downloads must be named by an owned page and stay
    in its directory. Unrecognised files are never cleared recursively.
    """
    if len(example_dirs) != len(gallery_dirs):
        raise ValueError("Each example directory must have one gallery directory")
    source_dir = source_dir.resolve()
    repo_root = source_dir.parents[1]
    tracked_output = subprocess.run(
        ["git", "ls-files", "-z", "--", "docs/source/examples"],
        cwd=repo_root,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    tracked = {repo_root / name for name in tracked_output.split("\0") if name}
    roots = {
        source_dir / gallery: (source_dir / example).resolve()
        for example, gallery in zip(example_dirs, gallery_dirs, strict=True)
    }
    removed: list[Path] = []
    examples_root = source_dir / "examples"
    for page in sorted(examples_root.rglob("*.rst")):
        if not is_ignored_artifact(page, tracked, repo_root):
            continue
        text = page.read_text(encoding="utf-8")
        if GENERATED_MARKER not in text[:350]:
            continue
        source_match = re.search(r'^\.\. "(examples/[^"\n]+\.py)"$', text, re.MULTILINE)
        if source_match is None:
            continue
        generated_script = source_dir / source_match[1]
        if generated_script != page.with_suffix(".py"):
            continue
        active_source = None
        for gallery_root, example_root in roots.items():
            if generated_script.is_relative_to(gallery_root):
                relative_script = generated_script.relative_to(gallery_root)
                active_source = example_root / relative_script
                break
        if (
            active_source is not None
            and active_source.is_file()
            and not re.search(ignore_pattern, active_source.as_posix())
        ):
            continue

        candidates = {page}
        for filename in re.findall(r":download:`[^`\n]*<([^>]+)>`", text):
            # Sphinx-Gallery names downloads after the example's stem.
            name = Path(filename)
            if (
                name.name == filename
                and name.stem == page.stem
                and name.suffix in {".py", ".ipynb", ".zip"}
            ):
                candidates.add(page.parent / name)
        candidates.update(
            page.with_name(page.stem + suffix)
            for suffix in (".codeobj.json", ".py.md5")
        )
        for candidate in sorted(candidates):
            if is_ignored_artifact(candidate, tracked, repo_root):
                candidate.unlink()
                removed.append(candidate)
    return removed


def clean_gallery_docs(app: Sphinx) -> None:
    """Use the configured source/output mapping before gallery generation."""
    gallery_config = app.config["sphinx_gallery_conf"]
    removed = clean_generated_galleries(
        Path(app.srcdir),
        gallery_config["examples_dirs"],
        gallery_config["gallery_dirs"],
        ignore_pattern=gallery_config["ignore_pattern"],
    )
    if removed:
        LOGGER.info("Removed %d obsolete generated gallery artifacts", len(removed))


def setup(app: Sphinx) -> dict[str, bool]:
    """Run cleanup before Sphinx-Gallery's builder-inited callback."""
    app.connect("builder-inited", clean_gallery_docs, priority=100)
    return {"parallel_read_safe": True}
