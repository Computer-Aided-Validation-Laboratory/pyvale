"""
Rendering linear and higher-order element types (SimData and VTK)
-----------------------------------------------------------------

This example demonstrates how ``pyvale.raytracer`` handles all supported
surface element types in a single scene:

* ``TET4``  -> ``TRI3``  (linear triangles, from Exodus ``SimData``)
* ``HEX8``  -> ``QUAD4`` (linear quads, from Exodus ``SimData``)
* ``HEX20`` -> ``QUAD8`` (8-node quadratic quads, from Exodus ``SimData``)
* ``HEX27`` -> ``QUAD9`` (9-node quadratic quads, from Exodus ``SimData``)
* ``TET10`` -> ``TRI6``  (6-node quadratic triangles, from Exodus ``SimData``)
* ``TRI3``  surface sphere loaded from a ``.vtk`` file via ``any_mesh_to_rtmesh``
"""

from pathlib import Path
import numpy as np
import pyvista as pv
from scipy.spatial.transform import Rotation

import pyvale.dataset as dataset
from pyvale.dataset import EElemTest
from pyvale.raytracer.rtcamera import Camera
from pyvale.raytracer.rtmain import render_scene
from pyvale.raytracer.rtmesh import (
    Anchor,
    Axis,
    MaterialType,
    SurfType,
    any_mesh_to_rtmesh,
    simdata_to_rtmesh,
)
from pyvale.raytracer.rtoutputformat import (
    BitDepth,
    ChannelCount,
    ImageFormat,
    OutputFormat,
    RenderType,
    ShadingType,
)
from pyvale.raytracer.rtscene import Scene

# %%
# Output directory and camera setup
# ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^

out_dir = Path.cwd() / "pyvale-output" / "raytracer" / "ex2_element_types"
out_dir.mkdir(parents=True, exist_ok=True)

scene = Scene()
image_width = 640
image_height = 360

camera = Camera(
    image_width=image_width,
    image_height=image_height,
    camera_center=np.array([0.0, 0.0, 0.0]),
    point_camera_target=np.array([0.0, 0.0, -1.0]),
    angle_vertical_view=24.0,
)
scene.add_camera(camera)

# %%
# Loading Exodus SimData meshes across element types
# ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
# ``pyvale.dataset.element_case_output_path`` provides 3D cube simulations for
# each supported volume element family. ``simdata_to_rtmesh`` automatically
# extracts the corresponding surface element type (``TRI3``, ``QUAD4``,
# ``QUAD8``, ``QUAD9``, or ``TRI6``).

cube_rot = Rotation.from_euler("xz", [35.0, 20.0], degrees=True)

simdata_specs = [
    (EElemTest.TET4,  np.array([-0.42,  0.14, -1.6]), np.array([0.85, 0.35, 0.35])),
    (EElemTest.HEX8,  np.array([ 0.00,  0.14, -1.6]), np.array([0.35, 0.75, 0.45])),
    (EElemTest.HEX20, np.array([ 0.42,  0.14, -1.6]), np.array([0.35, 0.55, 0.85])),
    (EElemTest.HEX27, np.array([-0.22, -0.15, -1.6]), np.array([0.85, 0.65, 0.25])),
    (EElemTest.TET10, np.array([ 0.22, -0.15, -1.6]), np.array([0.65, 0.40, 0.80])),
]

for elem_type, pos, colour in simdata_specs:
    exodus_path = dataset.element_case_output_path(elem_type)
    mesh = simdata_to_rtmesh(
        exodus_path,
        target_size=0.18,
        size_axis=Axis.Y,
        world_position=pos,
        anchor=Anchor.CENTER,
        world_rotation=cube_rot,
    )
    mesh.set_surface(
        surface_type=SurfType.FIELD_COLOR,
        surface_fill=colour,
        material_type=MaterialType.DIFFUSE,
    )
    scene.add_rtmesh(mesh)

# %%
# Loading an arbitrary VTK mesh with ``any_mesh_to_rtmesh``
# ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
# For non-Exodus meshes (e.g. ``.vtk``, ``.vtu``, ``.msh`` generated by Gmsh or
# PyVista), use ``any_mesh_to_rtmesh``. Here we write a triangulated sphere to
# disk and load it back via ``any_mesh_to_rtmesh``.

vtk_sphere_path = out_dir / "sphere_tri3.vtk"
sphere_grid = (
    pv.Sphere(radius=0.5, theta_resolution=24, phi_resolution=24)
    .triangulate()
    .cast_to_unstructured_grid()
)
sphere_grid.clear_data()
sphere_grid.save(vtk_sphere_path)

sphere_mesh = any_mesh_to_rtmesh(
    vtk_sphere_path,
    target_size=0.18,
    size_axis=Axis.Y,
    world_position=np.array([0.0, -0.15, -1.45]),
    anchor=Anchor.CENTER,
)
sphere_mesh.set_surface(
    surface_type=SurfType.FIELD_COLOR,
    surface_fill=np.array([0.25, 0.78, 0.78]),
    material_type=MaterialType.DIFFUSE,
)
scene.add_rtmesh(sphere_mesh)

# %%
# Rendering all element types together
# ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^

image_format = ImageFormat(
    output_format=OutputFormat.IMG_BMP_24BIT,
    bit_depth=BitDepth.BIT_8,
    channel_count=ChannelCount.RGB,
    grayscale=False,
)

render_scene(
    image_height=image_height,
    image_width=image_width,
    scene=scene,
    antialiasing_samples=8,
    out_directory_path=out_dir,
    render_type=RenderType.STATIC,
    shading_type=ShadingType.BLENDED,
    image_format=image_format,
)
