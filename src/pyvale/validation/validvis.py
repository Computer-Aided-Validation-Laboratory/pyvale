"""Visualisation options and PyVista views for validation results."""

from dataclasses import dataclass, field

import numpy as np
import pyvista as pv

from pyvale.dataio.simdata import SimData
from pyvale.sensorsim.fieldconverter import simdata_to_pyvista_vis
from pyvale.sensorsim.sensordescriptor import SensorDescriptor
from pyvale.sensorsim.visualopts import VisOptsSimSensors
from pyvale.sensorsim.visualtools import create_pv_plotter
from pyvale.validation.arraychecks import _validate_real_array
from pyvale.validation.imetric import (
    EMetricOut,
    EMetricScale,
    EMetricType,
)
from pyvale.validation.validtools import (
    _create_default_metric_labels,
    _create_metric_label,
    extract_metric_values,
)
from pyvale.validation.validtypes import EValidResAxis, ValidResult


@dataclass(slots=True)
class MetricVisOpts:
    """Metric/mesh appearance; camera, fonts and marker sizes use SensorSim options.

    Point labels are generated by the plot function from its descriptor.
    """

    metric_colour_lims: tuple[float, float] | None = None
    metric_cmap: str | None = None
    mesh_opacity: float = 0.6
    labels_always_visible: bool = False
    title: str | None = None
    metric_label: str | None = None
    metric_labels: dict[EMetricType, str] = field(
        default_factory=_create_default_metric_labels
    )


def create_valid_scene_opts(*, interactive: bool = False) -> VisOptsSimSensors:
    """Create validation scene defaults with independently labelled colourbars."""
    return VisOptsSimSensors(
        interactive=interactive,
        camera_position="iso",
        sens_point_size=18,
        sens_label_font_size=14,
        colour_bar_vertical=False,
        colour_bar_font_size=13,
    )


def _calculate_colour_limits(
    values: np.ndarray,
    limits: tuple[float, float] | None,
    *,
    magnitude: bool,
) -> tuple[float, float]:
    if limits is not None:
        lower, upper = limits
        if not np.all(np.isfinite(limits)) or lower >= upper:
            raise ValueError("Colour limits must be finite and strictly increasing.")
        if magnitude and lower < 0.0:
            raise ValueError("Magnitude metric colour limits cannot be negative.")
        return lower, upper
    finite = values[np.isfinite(values)]
    lower = 0.0 if magnitude or not len(finite) else float(np.min(finite))
    upper = float(np.max(finite)) if len(finite) else lower
    if upper == lower:
        padding = abs(lower) * 0.01 if lower != 0.0 else 1.0
        upper += padding
        if not magnitude:
            lower -= padding
    return lower, upper


def plot_metric_on_sim(
    result: ValidResult,
    observable: str,
    metric: EMetricType,
    *,
    selectors: dict[EValidResAxis, int] | None = None,
    output: EMetricOut | None = None,
    point_idxs: tuple[int, ...] | None = None,
    sim_data: SimData | None = None,
    sim_field: str | np.ndarray | None = None,
    sim_time_idx: int | None = None,
    descriptor: SensorDescriptor | None = None,
    sim_cmap: str = "viridis",
    sim_colour_lims: tuple[float, float] | None = None,
    sim_coord_units: str = "",
    sim_coord_frame: str = "",
    vis_opts: VisOptsSimSensors | None = None,
    metric_opts: MetricVisOpts | None = None,
    plotter: pv.Plotter | None = None,
) -> pv.Plotter:
    """Colour xyz validation points, optionally over an independently coloured mesh.

    The caller supplies the background run and declares its coordinate units and
    coord_frame; both must match the observable geometry. A time-resolved result must
    match the supplied background step exactly. No nearest-time selection,
    coordinate transformation, epistemic reduction or mesh interpolation occurs.
    NaN metrics remain grey points. Each numerical output is selected explicitly.
    A newly constructed plotter is off-screen by default; showing/saving is explicit.

    sim_field selects a nodal variable key or supplies derived values shaped
    (n_nodes,) at sim_time_idx. The descriptor labels the background colourbar
    and generates tags for all validation points before applying point_idxs.
    Without a descriptor, points are unlabelled and the background uses its key
    (or "Sim. field" for an array) as the colourbar label.
    """
    options = create_valid_scene_opts() if vis_opts is None else vis_opts
    metric_options = MetricVisOpts() if metric_opts is None else metric_opts
    field = result.metrics[observable][metric]
    output = field._resolve_output(output)
    values = extract_metric_values(field, selectors=selectors, output=output)
    observable_data = result.observables[observable]
    coords = observable_data.coords
    if coords is None:
        raise ValueError("Metric visualisation needs finite xyz point coordinates.")
    if (
        not np.isfinite(metric_options.mesh_opacity)
        or not 0 <= metric_options.mesh_opacity <= 1
    ):
        raise ValueError("Mesh opacity must be between zero and one.")
    if point_idxs is None:
        point_idxs = np.arange(len(coords))
    else:
        if not point_idxs or any(
            isinstance(point_idx, (bool, np.bool_))
            or not isinstance(point_idx, (int, np.integer))
            or not 0 <= point_idx < len(coords)
            for point_idx in point_idxs
        ):
            raise ValueError("Point subset must contain valid original point indices.")
        point_idxs = np.asarray(point_idxs)
    if sim_field is not None and sim_data is None:
        raise ValueError("A background field requires simulation data.")
    selected_values = values[point_idxs]
    metric_limits = _calculate_colour_limits(
        selected_values,
        metric_options.metric_colour_lims,
        magnitude=True,
    )
    mesh = None
    background_values: np.ndarray | None = None
    background_limits = None
    if sim_data is not None:
        if (
            sim_coord_units != observable_data.coord_units
            or sim_coord_frame != observable_data.coord_frame
        ):
            raise ValueError(
                "Simulation and validation coordinate units/coord_frame must match."
            )
        if sim_data.coords is None or not np.all(np.isfinite(sim_data.coords)):
            raise ValueError("Simulation needs finite xyz coordinates.")
        if sim_field is not None:
            if (
                isinstance(sim_time_idx, (bool, np.bool_))
                or not isinstance(sim_time_idx, (int, np.integer))
                or sim_data.time is None
                or not 0 <= sim_time_idx < sim_data.time.shape[0]
            ):
                raise ValueError("Select an explicit valid background time index.")
            if observable_data.times is not None:
                time_idx = (selectors or {}).get(EValidResAxis.TIME, 0)
                if sim_data.time[sim_time_idx] != observable_data.times[time_idx]:
                    raise ValueError(
                        "Background and validation physical times must match."
                    )
            if isinstance(sim_field, str):
                if sim_data.node_vars is None or sim_field not in sim_data.node_vars:
                    raise ValueError(f"Simulation has no nodal field {sim_field!r}.")
                background_values = sim_data.node_vars[sim_field][:, sim_time_idx]
            else:
                background_values = sim_field
            background_values = _validate_real_array(
                background_values, "Background scalar values"
            )
            if background_values.shape != (sim_data.coords.shape[0],):
                raise ValueError("Background scalar values must have shape (n_nodes,).")
            background_limits = _calculate_colour_limits(
                background_values,
                sim_colour_lims,
                magnitude=False,
            )
        mesh = simdata_to_pyvista_vis(sim_data, sim_data.num_spat_dims)
    background_label = sim_field if isinstance(sim_field, str) else "Sim. field"
    if descriptor is not None:
        background_label = descriptor.create_label_flat()
    pv_plot = create_pv_plotter(options) if plotter is None else plotter
    if mesh is not None:
        if background_values is None:
            pv_plot.add_mesh(
                mesh,
                name="validation-background",
                reset_camera=False,
                color="lightgrey",
                opacity=metric_options.mesh_opacity,
                show_edges=options.show_edges,
                show_scalar_bar=False,
            )
        else:
            mesh.point_data["background_scalar"] = background_values.copy()
            pv_plot.add_mesh(
                mesh,
                name="validation-background",
                reset_camera=False,
                scalars="background_scalar",
                opacity=metric_options.mesh_opacity,
                lighting=False,
                show_edges=options.show_edges,
                cmap=sim_cmap,
                clim=background_limits,
                show_scalar_bar=options.colour_bar_show,
                scalar_bar_args={
                    "title": f"Sim.: {background_label}",
                    "vertical": options.colour_bar_vertical,
                    "position_x": 0.02,
                    "position_y": 0.12,
                    "width": 0.10 if options.colour_bar_vertical else 0.40,
                    "height": 0.70 if options.colour_bar_vertical else 0.08,
                    "color": options.font_colour,
                    "title_font_size": options.colour_bar_font_size,
                    "label_font_size": options.colour_bar_font_size,
                },
            )
    point_mesh = pv.PolyData(coords[point_idxs].copy())
    point_mesh.point_data["validation_metric"] = selected_values.copy()
    point_mesh.point_data["validation_point_id"] = point_idxs.copy()
    units = (
        "-"
        if result.metric_configs[metric].get_scale() is not EMetricScale.PHYSICAL
        else observable_data.phys_units
    )
    units = "-" if units in ("1", "") else units
    metric_label = metric_options.metric_label or _create_metric_label(
        metric, output, metric_labels=metric_options.metric_labels
    )
    bar_label = metric_label
    component_idx = (selectors or {}).get(EValidResAxis.COMPONENT, 0)
    quantity_label = observable_data.components[component_idx]
    pv_plot.add_mesh(
        point_mesh,
        name="validation-points",
        reset_camera=False,
        scalars="validation_metric",
        style="points",
        render_points_as_spheres=True,
        point_size=options.sens_point_size,
        lighting=False,
        cmap=metric_options.metric_cmap or "magma",
        clim=metric_limits,
        nan_color="grey",
        show_scalar_bar=options.colour_bar_show,
        scalar_bar_args={
            "title": f"Validation: {quantity_label}\n{bar_label} [{units}]",
            "vertical": options.colour_bar_vertical,
            "position_x": 0.85 if options.colour_bar_vertical else 0.55,
            "position_y": 0.12,
            "width": 0.10 if options.colour_bar_vertical else 0.40,
            "height": 0.70 if options.colour_bar_vertical else 0.08,
            "color": options.font_colour,
            "title_font_size": options.colour_bar_font_size,
            "label_font_size": options.colour_bar_font_size,
            "nan_annotation": bool(np.any(np.isnan(selected_values))),
            "n_labels": 5,
        },
    )
    if descriptor is not None:
        point_tags = descriptor.create_sensor_tags(coords.shape[0])
        labels = [point_tags[selection_idx] for selection_idx in point_idxs]
        pv_plot.add_point_labels(
            point_mesh,
            labels,
            name="validation-labels",
            show_points=False,
            font_size=options.sens_label_font_size,
            text_color=options.font_colour,
            shape_color=options.sens_label_colour,
            always_visible=metric_options.labels_always_visible,
        )
    title = metric_options.title or f"{quantity_label}: {metric_label} [{units}]"
    pv_plot.add_text(
        title,
        position="upper_edge",
        font_size=options.time_label_font_size,
        color=options.font_colour,
        name="validation-title",
    )
    if options.time_label_pos is not None and observable_data.times is not None:
        selection_idx = (selectors or {}).get(EValidResAxis.TIME, 0)
        pv_plot.add_text(
            f"Time: {observable_data.times[selection_idx]:g} "
            f"{observable_data.time_units}",
            position=options.time_label_pos,
            font_size=options.time_label_font_size,
            color=options.font_colour,
            name="validation-time",
        )
    if plotter is None:
        pv_plot.camera_position = options.camera_position
        pv_plot.reset_camera()
        if sim_data is not None and sim_data.num_spat_dims == 3:
            pv_plot.camera.zoom(0.8)
    return pv_plot
